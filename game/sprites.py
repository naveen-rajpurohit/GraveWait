def _hood(map_str):
    """Archer: leather hood on the skull, bone body."""
    return "\n".join(
        "".join({"W": "L", "w": "L"}.get(ch, ch) for ch in row) if i < 2 else row
        for i, row in enumerate(map_str.splitlines()))


def _load_half(name):
    s = pygame.image.load(os.path.join(PACK_DIR, name)).convert_alpha()
    return pygame.transform.scale_by(s, 0.5)


def _tint(surf, color):
    s = surf.copy()
    s.fill(color, special_flags=pygame.BLEND_RGB_MULT)
    return s


def _flip_all(frames):
    """Pack enemies natively face LEFT; the game treats right as neutral."""
    return [pygame.transform.flip(f, True, False) for f in frames]


def _brighten(surf, amt=(30, 30, 42)):
    s = surf.copy()
    s.fill(amt, special_flags=pygame.BLEND_RGB_ADD)
    return s


def _outline(surf, color=(8, 6, 14)):
    """1px dark rim so enemies read against the murky background."""
    mask = pygame.mask.from_surface(surf)
    sil = mask.to_surface(setcolor=(*color, 255), unsetcolor=(0, 0, 0, 0))
    out = pygame.Surface((surf.get_width() + 2, surf.get_height() + 2),
                         pygame.SRCALPHA)
    for dx, dy in ((0, 1), (2, 1), (1, 0), (1, 2)):
        out.blit(sil, (dx, dy))
    out.blit(surf, (1, 1))
    return out


def _enemy_frames(names, ghost=False):
    frames = _flip_all(_load_half(n) for n in names)
    if ghost:
        frames = [_brighten(f) for f in frames]
    return [_outline(f) for f in frames]


def load_pack():
    """Override procedural entries with GothicVania Cemetery art if present."""
    global PACK
    if not os.path.isdir(PACK_DIR):
        return
    try:
        _S["player_idle"] = [_load_half(f"hero-idle-{i}.png") for i in range(1, 5)]
        _S["player_run"] = [_load_half(f"hero-run-{i}.png") for i in range(1, 7)]
        _S["player_attack"] = [_load_half(f"hero-attack-{i}.png") for i in range(1, 6)]
        _S["player_jump"] = [_load_half(f"hero-jump-{i}.png") for i in range(1, 5)]
        _S["player_crouch"] = [_load_half("hero-crouch.png")]
        _S["player_hurt"] = [_load_half("hero-hurt.png")]
        _S["skel_bare"] = _enemy_frames([f"skeleton-{i}.png" for i in range(1, 9)])
        _S["skel_sword"] = _enemy_frames([f"skeleton-clothed-{i}.png"
                                          for i in range(1, 9)])
        _S["skel_bare_rise"] = _enemy_frames([f"skeleton-rise-{i}.png"
                                              for i in range(1, 7)])
        _S["skel_sword_rise"] = _enemy_frames([f"skeleton-rise-clothed-{i}.png"
                                               for i in range(1, 7)])
        _S["enemy_death"] = _enemy_frames([f"enemy-death-{i}.png"
                                           for i in range(1, 6)])
        _S["skel_archer"] = _enemy_frames([f"ghost-{i}.png" for i in range(1, 5)],
                                          ghost=True)
        _S["skel_mage"] = _enemy_frames([f"ghost-halo-{i}.png"
                                         for i in range(1, 5)], ghost=True)
        # claude messenger: the hooded (clothed) skeleton as a spectral cyan ghost
        _S["skel_claude"] = [_tint(f, (150, 235, 255)) for f in _S["skel_sword"]]
        _S["grave1"] = [_load_half("stone-1.png")]
        _S["grave2"] = [_load_half("stone-2.png")]
        _S["grave3"] = [_load_half("stone-3.png")]
        _S["grave4"] = [_load_half("stone-4.png")]
        _S["statue"] = [_load_half("statue.png")]
        _S["bush_large"] = [_load_half("bush-large.png")]
        _S["bush_small"] = [_load_half("bush-small.png")]
        _S["bg_tree1"] = [_load_half("tree-1.png")]
        _S["bg_tree2"] = [_load_half("tree-2.png")]
        _S["bg_tree3"] = [_load_half("tree-3.png")]
        PACK = True
    except (pygame.error, FileNotFoundError, OSError):
        PACK = False


def has(name):
    return name in _S


def load_layer_half(filename):
    """Half-scale environment layer from the pack, or None."""
    try:
        return _load_half(filename)
    except (pygame.error, FileNotFoundError, OSError):
        return None


def get(name):
    return _S[name]


_flip_cache = {}


def flipped(surf):
    key = id(surf)
    if key not in _flip_cache:
        _flip_cache[key] = pygame.transform.flip(surf, True, False)
    return _flip_cache[key]


_white_cache = {}


def white(surf):
    """Solid-white silhouette for hit flashes."""
    key = id(surf)
    if key not in _white_cache:
        s = surf.copy()
        s.fill((255, 255, 255), special_flags=pygame.BLEND_RGB_MAX)
        _white_cache[key] = s
    return _white_cache[key]
