def _surf(map_str):
    rows = [r for r in map_str.splitlines() if r]
    w = max(len(r) for r in rows)
    s = pygame.Surface((w, len(rows)), pygame.SRCALPHA)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch != ".":
                s.set_at((x, y), PAL[ch])
    return s


def _recolor(map_str, table, from_row=0):
    rows = map_str.splitlines()
    out = []
    for i, row in enumerate(rows):
        if i >= from_row:
            row = "".join(table.get(ch, ch) for ch in row)
        out.append(row)
    return "\n".join(out)


